// Downloads the display + mono fonts (Oxanium, Orbitron, Chakra Petch, Press
// Start 2P, VT323, JetBrains Mono — all SIL OFL 1.1) as local woff2 and emits
// src/renderer/src/assets/fonts/fonts.css. Offline-first: the app never fetches
// fonts at runtime. Attribution + license: see THIRD-PARTY-LICENSES.md and
// src/renderer/src/assets/fonts/OFL.txt. Node 20+ (global fetch). Run once:
//   node scripts/fetch-fonts.cjs
const fs = require('fs')
const path = require('path')

const OUT = path.join(__dirname, '..', 'src', 'renderer', 'src', 'assets', 'fonts')
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'
const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Oxanium:wght@500;600;700;800&family=Orbitron:wght@600;800&family=Chakra+Petch:wght@600;700&family=Press+Start+2P&family=VT323&family=JetBrains+Mono:wght@400;500;700&display=swap'
const KEEP_SUBSETS = new Set(['latin', 'latin-ext'])

async function main() {
  fs.mkdirSync(OUT, { recursive: true })
  const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text()

  const re = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g
  const faces = []
  let m
  while ((m = re.exec(css))) {
    const [subset, body] = [m[1], m[2]]
    if (!KEEP_SUBSETS.has(subset)) continue
    const family = /font-family:\s*'([^']+)'/.exec(body)?.[1]
    const weight = /font-weight:\s*(\d+)/.exec(body)?.[1]
    const url = /src:\s*url\(([^)]+)\)/.exec(body)?.[1]
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]
    if (family && weight && url) faces.push({ subset, family, weight, url, range })
  }

  const lines = ['/* Generated by scripts/fetch-fonts.cjs — do not edit by hand. */']
  for (const f of faces) {
    const slug = `${f.family.replace(/\s+/g, '')}-${f.weight}-${f.subset}.woff2`
    const buf = Buffer.from(await (await fetch(f.url, { headers: { 'User-Agent': UA } })).arrayBuffer())
    fs.writeFileSync(path.join(OUT, slug), buf)
    console.log('saved', slug, buf.length, 'bytes')
    lines.push(
      `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${f.weight};font-display:swap;` +
        `src:url('./${slug}') format('woff2');` +
        (f.range ? `unicode-range:${f.range};` : '') +
        `}`
    )
  }
  fs.writeFileSync(path.join(OUT, 'fonts.css'), lines.join('\n') + '\n')
  console.log(`\nwrote fonts.css with ${faces.length} faces`)
}

main().catch((e) => {
  console.error('FAILED:', e.message)
  process.exit(1)
})
